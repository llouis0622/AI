export type IconName = keyof typeof ICONS | 'github';
export const iconNames = [...Object.keys(ICONS), 'github'] as IconName[];

type Props = {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  className?: string;
  /** Accessible label. Without one the icon is decorative (aria-hidden). */
  title?: string;
} & Omit<SVGProps<SVGSVGElement>, 'name' | 'ref' | 'children'>;

export default function Icon({ name, size = 18, strokeWidth = 1.75, className, title, ...rest }: Props) {
  const a11y = title ? { role: 'img', 'aria-label': title } : { 'aria-hidden': true as const };
  const cls = `icon${className ? ` ${className}` : ''}`;
  if (name === 'github') {
    // Lucide dropped brand marks, so this one is drawn here.
    return (
      <svg
        xmlns="http://www.w3.org/2000/svg"
        width={size}
        height={size}
        viewBox="0 0 24 24"
        fill="none"
        stroke="currentColor"
        strokeWidth={strokeWidth}
        strokeLinecap="round"
        strokeLinejoin="round"
        className={cls}
        {...a11y}
        {...rest}
      >
        <path d="M9 19c-4.3 1.4-4.3-2.5-6-3m12 5v-3.5c0-1 .1-1.4-.5-2 2.8-.3 5.5-1.4 5.5-6a4.6 4.6 0 0 0-1.3-3.2 4.2 4.2 0 0 0-.1-3.2s-1.1-.3-3.5 1.3a12.3 12.3 0 0 0-6.2 0C6.5 2.8 5.4 3.1 5.4 3.1a4.2 4.2 0 0 0-.1 3.2A4.6 4.6 0 0 0 4 9.5c0 4.6 2.7 5.7 5.5 6-.6.6-.6 1.2-.5 2V21" />
      </svg>
    );
  }
  const C = ICONS[name];
  return <C size={size} strokeWidth={strokeWidth} className={cls} {...a11y} {...rest} />;
}
